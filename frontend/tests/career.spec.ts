import { join } from 'node:path'
import { test, expect } from '@playwright/test'

test('Штаб, брифинг, загрузка и перенос сохранения', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto('/')
  await page.getByLabel('Имя игрока').fill('Инженер приёмки')
  await page
    .getByRole('combobox', { name: 'Организация', exact: true })
    .selectOption('team-mclaren-formula-1-team')
  await page.getByLabel('Seed мира').fill('42')
  await page.getByRole('button', { name: 'Создать карьеру' }).click()
  await expect(page.getByRole('heading', { name: 'Штаб команды' })).toBeVisible()
  const original = page.url()
  const next = page.getByRole('button', { name: 'Продолжить' })
  await next.click()
  const briefing = page.getByRole('button', { name: 'Брифинг', exact: true })
  await briefing.click()
  await expect(page.getByRole('dialog')).toContainText('McLaren MCL39')
  await page.getByRole('button', { name: 'Подтвердить брифинг' }).click()
  await page.reload()
  await expect(page.locator('.top-date')).toContainText('13 февраля')
  await page.getByRole('link', { name: 'К календарю' }).click()
  await expect(page.getByRole('heading', { name: 'Календарь', exact: true })).toBeVisible()
  await expect(page.getByLabel('Программа')).toHaveValue('f1')
  await page.getByLabel('Программа').selectOption('wec')
  await page.getByRole('button', { name: 'Список', exact: true }).click()
  await page.getByRole('button', { name: /21 февраля.*пролог/ }).click()
  await expect(page.locator('.event-detail')).toContainText('Lusail')
  await page.getByRole('button', { name: 'Сохранение карьеры' }).click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Экспорт JSON' }).click()
  const download = await downloading
  const file = await download.path()
  await page.getByRole('link', { name: 'К списку карьер' }).click()
  await page
    .getByLabel('Импортировать сохранение')
    .setInputFiles({ name: 'broken.json', mimeType: 'application/json', buffer: Buffer.from('{}') })
  await expect(page.getByRole('alert')).toContainText('Неизвестный формат')
  await page.getByLabel('Импортировать сохранение').setInputFiles(file!)
  await expect(page.getByRole('heading', { name: 'Штаб команды' })).toBeVisible()
  expect(page.url()).not.toBe(original)
  await expect(page.locator('.top-date')).toContainText('13 февраля')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(page.viewportSize()!.width)
  expect(errors).toEqual([])
})
test('Владелец DTM и шинный поставщик WEC работают в отдельных сохранениях', async ({ page }) => {
  const mobile = page.viewportSize()!.width < 760
  async function screen(id: string, label: string) {
    if (mobile && !['overview', 'people', 'calendar'].includes(id))
      await page.getByRole('button', { name: 'Ещё' }).click()
    await page.getByRole('link', { name: label, exact: true }).filter({ visible: true }).first().click()
  }
  async function evidence(id: string) {
    await page.evaluate(() => document.fonts.ready)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(page.viewportSize()!.width)
    if (process.env.CAREER_EVIDENCE)
      await page.screenshot({
        path: join(process.env.CAREER_EVIDENCE, (mobile ? 'mobile' : 'desktop') + '-' + id + '.png'),
      })
  }
  await page.goto('/')
  await page.getByRole('heading', { name: 'Карьера в автоспорте' }).waitFor()
  await evidence('library')
  await page.getByRole('button', { name: /Владелец команды/ }).click()
  await page.getByRole('combobox', { name: 'Чемпионат' }).selectOption('dtm')
  await page.getByRole('combobox', { name: 'Организация' }).selectOption('team-abt-sportsline')
  await page.getByLabel('Имя игрока').fill('Алекс')
  await page.getByRole('button', { name: 'Создать карьеру' }).click()
  await expect(page.getByRole('heading', { name: 'Штаб владельца' })).toBeVisible()
  await expect(page.getByRole('main')).toContainText('Mirko Bortolotti')
  await evidence('headquarters')
  await screen('people', mobile ? 'Состав' : 'Пилоты и персонал')
  await page.getByRole('button', { name: /Mirko Bortolotti/ }).click()
  await expect(page.getByRole('dialog')).toContainText('Выносливость')
  await expect(page.getByRole('dialog').getByRole('img', { name: /силуэт/ })).toBeVisible()
  await evidence('dossier')
  await page.getByRole('button', { name: 'Закрыть' }).click()
  await page.goto('/')
  await page.getByRole('button', { name: /Производитель Разработка/ }).click()
  await page.getByRole('combobox', { name: 'Чемпионат' }).selectOption('wec')
  await page.getByRole('combobox', { name: 'Организация' }).selectOption('supplier-goodyear')
  await page.getByLabel('Имя игрока').fill('Ирина')
  await page.getByRole('button', { name: 'Создать карьеру' }).click()
  await expect(page.getByRole('heading', { name: 'Штаб производителя' })).toBeVisible()
  await expect(page.getByRole('main')).toContainText('Шины')
  await expect(page.getByRole('main')).toContainText('Iron Dames')
  await expect(page.getByRole('main')).not.toContainText('Ferrari 499P')
  await screen('world', 'Чемпионаты')
  await expect(page.getByRole('main')).toContainText('Единый поставщик · Michelin')
  await expect(page.getByRole('main')).toContainText('Единый поставщик · Goodyear')
  await evidence('championship')
})
