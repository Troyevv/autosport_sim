import { configureCareer, submitCareer } from './createCareer'
import { join } from 'node:path'
import { test, expect } from '@playwright/test'

test('Штаб, брифинг, загрузка и перенос сохранения', async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto('/')
  await configureCareer(page, { name: 'Инженер приёмки' })
  await submitCareer(page)
  await expect(page.getByRole('heading', { name: 'Команда ждёт вашего решения.' })).toBeVisible({ timeout: 15000 })
  const original = page.url()
  const next = page.getByRole('button', { name: 'Продолжить' })
  await next.click()
  const briefing = page.getByRole('button', { name: 'Брифинг', exact: true })
  await briefing.click()
  await expect(page.getByRole('dialog')).toContainText('McLaren MCL39')
  await page.getByRole('button', { name: 'Подтвердить брифинг' }).click()
  await page.reload()
  await expect(page.locator('.topbar-date')).toContainText('13 февраля')
  await page.getByRole('button', { name: 'Календарь', exact: true }).filter({visible:true}).first().click()
  await expect(page.getByRole('heading', { name: 'Календарь', exact: true })).toBeVisible()
  await expect(page.getByRole('combobox', {name:'Чемпионат',exact:true})).toHaveValue('f1')
  await page.getByRole('combobox', {name:'Чемпионат',exact:true}).selectOption('wec')
  await page.getByRole('tab', { name: 'Хронология', exact: true }).click()
  await page.locator('.calendar-list button').filter({hasText:/пролог/i}).first().click()
  await expect(page.getByRole('dialog')).toContainText('Lusail')
  await page.keyboard.press('Escape')
  await page.locator('.topbar').getByRole('button', { name: 'Сохранение карьеры' }).click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Экспорт сохранения' }).click()
  const download = await downloading
  const file = await download.path()
  await page.getByRole('link', { name: 'К списку карьер' }).click()
  await page
    .getByLabel('Импортировать сохранение')
    .setInputFiles({ name: 'broken.json', mimeType: 'application/json', buffer: Buffer.from('{}') })
  await expect(page.getByRole('alert')).toContainText('Неизвестный формат')
  const importing = page.waitForResponse(
    (response) => response.url().endsWith('/api/careers/import') && response.request().method() === 'POST',
  )
  await page.getByLabel('Импортировать сохранение').setInputFiles(file!)
  expect((await importing).status()).toBe(201)
  await expect(page.getByRole('heading', { name: 'Команда ждёт вашего решения.' })).toBeVisible({ timeout: 15000 })
  expect(page.url()).not.toBe(original)
  await expect(page.locator('.topbar-date')).toContainText('13 февраля')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(page.viewportSize()!.width)
  expect(errors).toEqual([])
})
test('Владелец DTM и шинный поставщик WEC работают в отдельных сохранениях', async ({ page }) => {
  const mobile = page.viewportSize()!.width < 760
  async function evidence(id: string) {
    await page.evaluate(() => document.fonts.ready)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(page.viewportSize()!.width)
    if (process.env.CAREER_EVIDENCE)
      await page.screenshot({
        path: join(process.env.CAREER_EVIDENCE, (mobile ? 'mobile' : 'desktop') + '-' + id + '.png'),
      })
  }
  await page.goto('/')
  await page.locator('.title-copy').waitFor()
  await evidence('library')
  await configureCareer(page, { role: 'owner', series: 'dtm', org: 'team-abt-sportsline' })
  await submitCareer(page)
  await expect(page.getByRole('heading', { name: 'Вы задаёте направление.' })).toBeVisible()
  const world = await (await page.request.get('/api/world')).json()
  const driver = world.names[world.entries['dtm-1'].crew[0]]
  await expect(page.locator('.role-home')).toContainText('ABT')
  await evidence('headquarters')
  await page.goto(page.url().split('#')[0] + '#people')
  await page.getByRole('button', { name: new RegExp(driver) }).click()
  await expect(page.locator('.staff-dossier')).toContainText('Выносливость')
  await expect(page.locator('.staff-dossier').locator('image[data-layer="fitted-fabric"]')).toHaveCount(1)
  await expect(page.locator('.staff-dossier')).toContainText('Специализация')
  await evidence('dossier')
  await page.getByRole('button', { name: /К списку/ }).click()
  await page.goto('/')
  await configureCareer(page, { role: 'manufacturer', series: 'wec', org: 'supplier-goodyear', name: 'Ирина' })
  await submitCareer(page)
  await expect(page.getByRole('heading', { name: 'Клиенты рассчитывают на вашу технику.' })).toBeVisible()
  await expect(page.getByRole('main')).toContainText('Шины')
  await expect(page.locator('.role-home')).toContainText('Goodyear')
  await expect(page.getByRole('main')).not.toContainText('Ferrari 499P')
  await page.goto(page.url().split('#')[0] + '#world')
  await page.getByRole('tab', {name:'Регламент'}).click()
  await expect(page.getByRole('main')).toContainText('Единый поставщик · Michelin')
  await expect(page.getByRole('main')).toContainText('Единый поставщик · Goodyear')
  await evidence('championship')
})

test('Встроенная галерея сохраняет лицо при смене формы', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Портреты и форма' }).click()
  await expect(page.locator('.studio-grid image[data-layer="appearance"]')).toHaveCount(12)
  await page.getByRole('button', { name: 'Сравнить комплекты' }).click()
  const picker = page.getByRole('combobox', { name: 'Персонаж' })
  const reserve = picker.locator('option').filter({ hasText: /^Резерв · 1$/ })
  const face = await reserve.getAttribute('value')
  expect(face).toBeTruthy()
  await picker.selectOption(face!)
  const heads = page.locator('figure image[data-layer="appearance"]')
  await expect(heads).toHaveCount(5)
  const hrefs = await heads.evaluateAll((nodes) => nodes.map((node) => node.getAttribute('href')))
  expect(new Set(hrefs).size).toBe(1)
  expect(hrefs[0]).toContain(face)
  const garments = page.locator('figure image[data-layer="fitted-fabric"]')
  await expect(garments).toHaveCount(5)
  const fabrics = await garments.evaluateAll((nodes) => nodes.map((node) => node.getAttribute('href')))
  expect(new Set(fabrics).size).toBe(5)
})
